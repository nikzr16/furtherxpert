const ALERT_TONES = {
  success: { box: 'border-emerald-200 bg-emerald-50 text-emerald-900', icon: 'checkCircle', iconColor: 'text-emerald-600' },
  warning: { box: 'border-amber-200 bg-amber-50 text-amber-900', icon: 'warning', iconColor: 'text-amber-600' },
  error: { box: 'border-red-200 bg-red-50 text-red-900', icon: 'warning', iconColor: 'text-red-600' },
  info: { box: 'border-indigo-200 bg-indigo-50 text-indigo-900', icon: 'info', iconColor: 'text-indigo-600' },
}

export function Alert({ tone = 'info', title, children, className = '' }) {
  const style = ALERT_TONES[tone]
  return (
    <div
      className={`flex gap-3 rounded-xl border px-4 py-3 text-sm ${style.box} ${className}`}
      role={tone === 'error' ? 'alert' : undefined}
    >
      <Icon name={style.icon} className={`mt-px size-5 shrink-0 ${style.iconColor}`} />
      <div className="min-w-0 leading-relaxed">
        {title && <p className="font-semibold">{title}</p>}
        {children}
      </div>
    </div>
  )
}

